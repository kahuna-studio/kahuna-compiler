//! Writes the generated Rust crate of an instrument: `Cargo.toml`, `src/lib.rs`, `src/patch.rs`
//! and `src/main.rs`.
//!
//! Only files are written, never directories removed, so cargo's `target/` next to them survives
//! and a second build with an unchanged patch is a no-op: a file whose contents wouldn't change is
//! left alone, because cargo rebuilds a crate when a source file's modification time changes.

use std::fs;
use std::path::{Path, PathBuf};

use eyre::{ensure, Result, WrapErr};

use crate::compilation_steps::instrument_file_parser::instrument_metadata::InstrumentMetadata;

/// The first line of every generated file.
pub const GENERATED_NOTICE: &str = "Generated by kahuna-compiler. Do not edit.";

/// How many frames the runtime asks the patch to process at most per call.
const MAX_BUFFER_SIZE: usize = 2048;

/// Crates of the toolchain that every generated crate depends on, next to the libraries.
const TOOLCHAIN_DEPENDENCIES: [&str; 2] = ["kahuna-core", "kahuna-runtime"];

/// One entry of the generated crate's `[dependencies]`.
#[derive(Debug, Clone, PartialEq)]
pub struct CargoDependency {
  pub key: String,
  /// The Cargo dependency specification, with absolute paths.
  pub specification: toml::Value,
}

/// The directory of the generated Rust project inside the output directory (`.kahuna/rust`). The
/// name is fixed, not the instrument's: `.kahuna/` holds other things as well, e.g. `bin/`, and an
/// instrument called `bin` must not collide with them.
pub const RUST_DIR: &str = "rust";

pub fn crate_dir(output_dir: &Path) -> PathBuf {
  output_dir.join(RUST_DIR)
}

/// Until the compiler is installed separately from the toolchain repository, the crates of the
/// toolchain (`kahuna-core`, `kahuna-runtime`, `kahuna-std`) are found next to the compiler's own.
///
/// Every dependency on `kahuna-core` must resolve to this one path: units in `kahuna-std` implement
/// its traits, and a second copy would make those impls belong to a different trait.
pub fn toolchain_crate_dir(name: &str) -> PathBuf {
  Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join(name)
}

/// The generated crate lives elsewhere, so the path to a dependency is made absolute.
pub fn path_specification(directory: &Path) -> Result<toml::Value> {
  let path = directory
    .canonicalize()
    .wrap_err_with(|| format!("Directory not found: {}", directory.display()))?;
  let path = path.to_string_lossy().into_owned();
  Ok(toml::Value::Table(toml::Table::from_iter([("path".to_string(), path.into())])))
}

/// `Cargo.toml` with the libraries only, and `src/lib.rs`: enough for `cargo metadata` to say where
/// the libraries are, before any code has been generated.
pub fn write_probe_crate(crate_dir: &Path, metadata: &InstrumentMetadata, libraries: &[CargoDependency]) -> Result<()> {
  write_manifest(crate_dir, metadata, libraries)?;
  write_library_root(crate_dir)
}

/// The complete crate: everything `write_probe_crate` writes, with `kahuna-core` and
/// `kahuna-runtime` as dependencies as well, plus `src/patch.rs` and `src/main.rs`.
pub fn write_crate(
  crate_dir: &Path,
  metadata: &InstrumentMetadata,
  libraries: &[CargoDependency],
  patch_source: &str,
) -> Result<()> {
  let mut dependencies = libraries.to_vec();
  for name in TOOLCHAIN_DEPENDENCIES {
    ensure!(
      !libraries.iter().any(|library| library.key == name),
      "A library is named '{name}', which the generated crate needs as a dependency; rename its package"
    );
    dependencies.push(CargoDependency {
      key: name.to_string(),
      specification: path_specification(&toolchain_crate_dir(name))?,
    });
  }

  write_manifest(crate_dir, metadata, &dependencies)?;
  write_library_root(crate_dir)?;
  write_file(&crate_dir.join("src/patch.rs"), &format!("// {GENERATED_NOTICE}\n\n{patch_source}"))?;
  write_file(&crate_dir.join("src/main.rs"), &main_source(metadata))
}

fn write_manifest(crate_dir: &Path, metadata: &InstrumentMetadata, dependencies: &[CargoDependency]) -> Result<()> {
  let package = toml::Table::from_iter([
    ("name".to_string(), metadata.name.clone().into()),
    ("version".to_string(), metadata.version.clone().into()),
    ("edition".to_string(), "2024".into()),
    ("publish".to_string(), false.into()),
  ]);
  let dependency_table = dependencies
    .iter()
    .map(|dependency| (dependency.key.clone(), dependency.specification.clone()))
    .collect::<toml::Table>();
  let cargo_toml = toml::Table::from_iter([
    ("package".to_string(), package.into()),
    // Its own workspace, even when the instrument sits inside another one.
    ("workspace".to_string(), toml::Table::new().into()),
    ("dependencies".to_string(), dependency_table.into()),
  ]);

  write_file(&crate_dir.join("Cargo.toml"), &format!("# {GENERATED_NOTICE}\n\n{}", toml::to_string(&cargo_toml)?))
}

/// The one place that writes `src/lib.rs`: the patch is a module of a library, so other crates can
/// use it later (a plugin around the same patch), and the executable is a thin `main.rs` on top.
fn write_library_root(crate_dir: &Path) -> Result<()> {
  write_file(&crate_dir.join("src/lib.rs"), &format!("// {GENERATED_NOTICE}\n\npub mod patch;\n"))
}

fn main_source(metadata: &InstrumentMetadata) -> String {
  // What cargo calls the library of a package: the package name with underscores.
  let library = metadata.name.replace('-', "_");
  format!(
    "// {GENERATED_NOTICE}\n\
     \n\
     use kahuna_runtime::run_standalone;\n\
     use {library}::patch::Patch;\n\
     \n\
     fn main() {{\n\
     \x20 run_standalone({MAX_BUFFER_SIZE}, |sample_rate, max_buffer_size, factory| {{\n\
     \x20   Patch::new(sample_rate, max_buffer_size, factory)\n\
     \x20 }});\n\
     }}\n"
  )
}

/// Leaves a file alone when it already has these contents.
fn write_file(path: &Path, contents: &str) -> Result<()> {
  if fs::read_to_string(path).is_ok_and(|existing| existing == contents) {
    return Ok(());
  }
  if let Some(directory) = path.parent() {
    fs::create_dir_all(directory).wrap_err_with(|| format!("Cannot create {}", directory.display()))?;
  }
  fs::write(path, contents).wrap_err_with(|| format!("Cannot write {}", path.display()))
}

#[cfg(test)]
mod tests {
  use std::time::{Duration, UNIX_EPOCH};

  use super::*;

  fn metadata() -> InstrumentMetadata {
    InstrumentMetadata::from_str("name = \"my-synth\"\nvendor = \"Kahuna Studio\"\nversion = \"0.2.0\"\n").unwrap()
  }

  fn library(key: &str) -> CargoDependency {
    CargoDependency {
      key: key.to_string(),
      specification: path_specification(&toolchain_crate_dir("kahuna-std")).unwrap(),
    }
  }

  fn scratch_dir(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("kahuna-crate-writer-{name}-{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    dir
  }

  fn read(crate_dir: &Path, file: &str) -> String {
    fs::read_to_string(crate_dir.join(file)).unwrap()
  }

  #[test]
  fn writes_the_four_files_each_starting_with_the_generated_notice() {
    let crate_dir = scratch_dir("files");

    write_crate(&crate_dir, &metadata(), &[library("kahuna-std")], "pub struct Patch;\n").unwrap();

    for file in ["Cargo.toml", "src/lib.rs", "src/patch.rs", "src/main.rs"] {
      let first_line = read(&crate_dir, file).lines().next().unwrap().to_string();
      assert!(first_line.ends_with(GENERATED_NOTICE), "{file}: {first_line}");
    }
    assert!(read(&crate_dir, "src/lib.rs").contains("\npub mod patch;\n"));
    assert!(read(&crate_dir, "src/patch.rs").ends_with("pub struct Patch;\n"));
  }

  #[test]
  fn main_runs_the_patch_of_the_library_with_the_runtime() {
    let crate_dir = scratch_dir("main");

    write_crate(&crate_dir, &metadata(), &[], "").unwrap();

    let main = read(&crate_dir, "src/main.rs");
    assert!(main.contains("use my_synth::patch::Patch;"), "{main}");
    assert!(main.contains("run_standalone(2048, |sample_rate, max_buffer_size, factory| {"), "{main}");
    assert!(main.contains("Patch::new(sample_rate, max_buffer_size, factory)"), "{main}");
  }

  #[test]
  fn cargo_toml_depends_on_the_toolchain_by_absolute_path_and_is_its_own_workspace() {
    let crate_dir = scratch_dir("manifest");

    write_crate(&crate_dir, &metadata(), &[library("kahuna-std")], "").unwrap();

    let cargo_toml: toml::Table = read(&crate_dir, "Cargo.toml").parse().unwrap();
    assert_eq!(cargo_toml["package"]["name"].as_str(), Some("my-synth"));
    assert_eq!(cargo_toml["package"]["version"].as_str(), Some("0.2.0"));
    assert!(cargo_toml.contains_key("workspace"));
    for name in ["kahuna-core", "kahuna-runtime", "kahuna-std"] {
      let path = Path::new(cargo_toml["dependencies"][name]["path"].as_str().unwrap());
      assert!(path.is_absolute(), "{name}: {path:?}");
      assert_eq!(path, toolchain_crate_dir(name).canonicalize().unwrap(), "{name}");
    }
  }

  #[test]
  fn the_probe_crate_has_the_libraries_and_a_library_root_only() {
    let crate_dir = scratch_dir("probe");

    write_probe_crate(&crate_dir, &metadata(), &[library("kahuna-std")]).unwrap();

    let cargo_toml: toml::Table = read(&crate_dir, "Cargo.toml").parse().unwrap();
    assert_eq!(cargo_toml["dependencies"].as_table().unwrap().keys().collect::<Vec<_>>(), ["kahuna-std"]);
    assert!(crate_dir.join("src/lib.rs").is_file());
    assert!(!crate_dir.join("src/main.rs").exists());
  }

  #[test]
  fn the_complete_crate_replaces_the_probe_crate() {
    let crate_dir = scratch_dir("replace-probe");
    write_probe_crate(&crate_dir, &metadata(), &[library("kahuna-std")]).unwrap();

    write_crate(&crate_dir, &metadata(), &[library("kahuna-std")], "").unwrap();

    let cargo_toml: toml::Table = read(&crate_dir, "Cargo.toml").parse().unwrap();
    assert!(cargo_toml["dependencies"].as_table().unwrap().contains_key("kahuna-runtime"));
    assert_eq!(read(&crate_dir, "src/lib.rs").matches("pub mod patch;").count(), 1);
  }

  #[test]
  fn overwrites_files_and_keeps_the_build_cache() {
    let crate_dir = scratch_dir("overwrite");
    write_crate(&crate_dir, &metadata(), &[], "// first\n").unwrap();
    fs::create_dir_all(crate_dir.join("target/release")).unwrap();
    fs::write(crate_dir.join("target/release/cached"), "build output").unwrap();

    write_crate(&crate_dir, &metadata(), &[], "// second\n").unwrap();

    assert!(read(&crate_dir, "src/patch.rs").ends_with("// second\n"));
    assert_eq!(read(&crate_dir, "target/release/cached"), "build output");
  }

  #[test]
  fn files_with_unchanged_contents_are_not_touched() {
    let crate_dir = scratch_dir("unchanged");
    write_crate(&crate_dir, &metadata(), &[library("kahuna-std")], "// patch\n").unwrap();
    let long_ago = UNIX_EPOCH + Duration::from_secs(1_000_000);
    let files = ["Cargo.toml", "src/lib.rs", "src/patch.rs", "src/main.rs"];
    for file in files {
      fs::File::options().write(true).open(crate_dir.join(file)).unwrap().set_modified(long_ago).unwrap();
    }

    write_crate(&crate_dir, &metadata(), &[library("kahuna-std")], "// patch\n").unwrap();

    for file in files {
      let modified = fs::metadata(crate_dir.join(file)).unwrap().modified().unwrap();
      assert_eq!(modified, long_ago, "{file} was rewritten although nothing changed");
    }
  }

  #[test]
  fn rejects_a_library_that_is_named_like_a_toolchain_dependency() {
    for name in TOOLCHAIN_DEPENDENCIES {
      let error = write_crate(&scratch_dir("clash"), &metadata(), &[library(name)], "").unwrap_err();

      assert!(format!("{error}").contains(&format!("'{name}'")), "{error}");
    }
  }
}
